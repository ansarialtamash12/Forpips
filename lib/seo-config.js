// Helper function to generate metadata for a page
export function generateMetadata(pageKey) {
  const config = SEO_CONFIG[pageKey];
  if (!config) {
    return SEO_CONFIG.home;
  }

  return {
    title: config.title,
    description: config.description,
    keywords: config.keywords,
    robots: "index,follow",
    authors: [{ name: "Forpips" }],
    copyright: "Forpips Education",
    openGraph: {
      title: config.ogTitle,
      description: config.ogDescription,
      url: config.canonical,
      siteName: SITE_NAME,
      locale: "en_US",
      type: "website",
      images: [
        {
          url: config.ogImage,
          width: 1200,
          height: 630,
          alt: config.ogTitle,
        },
      ],
    },
    alternates: {
      canonical: config.canonical,
      languages: {
        en: config.canonical,
      },
    },
    twitter: {
      card: "summary_large_image",
      title: config.ogTitle,
      description: config.ogDescription,
      images: [config.ogImage],
    },
  };
}
